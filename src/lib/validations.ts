/** 14 dígitos -> 00.000.000/0000-00 (outros valores voltam como vieram). */
export function formatCnpj(v: string) {
  const d = (v ?? "").replace(/\D/g, "");
  return d.length === 14
    ? `${d.slice(0, 2)}.${d.slice(2, 5)}.${d.slice(5, 8)}/${d.slice(8, 12)}-${d.slice(12)}`
    : v;
}
